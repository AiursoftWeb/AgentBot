using Aiursoft.AgentBot.Models;
using Aiursoft.AgentBot.Services;

namespace Aiursoft.AgentBot.Tests;

[TestClass]
public class MergeRequestAutomationBudgetTests
{
    [TestMethod]
    public void ReservationAndCompletedReviewCountAsOneRound()
    {
        var marker = MergeRequestAutomationBudget.Marker("review", 1);
        var notes = new[] { Own(marker), Own("Approved\n" + marker + "\n<!-- agentbot:mr-review:commit-abcdef0123 -->") };
        Assert.AreEqual(1, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "review"));
        Assert.AreEqual(0, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "repair"));
    }

    [TestMethod]
    public void LegacyLoopDoesNotGetNewAllowanceAfterDeployment()
    {
        var notes = Enumerable.Range(0, 79).Select(n => Own($"<!-- agentbot:mr-review:commit-{n:x40} -->")).ToList();
        Assert.AreEqual(79, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "review"));
        Assert.AreEqual(2, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "repair"));
    }

    [TestMethod]
    public void HumanQuotesAndOtherBotsCannotConsumeBudget()
    {
        var notes = new[]
        {
            new GitLabNote { Author = new GitLabUser { Username = "human" }, Body = MergeRequestAutomationBudget.Marker("review", 2) },
            new GitLabNote { Author = new GitLabUser { Username = "other-bot" }, Body = MergeRequestAutomationBudget.Marker("repair", 2) },
            new GitLabNote { System = true, Author = new GitLabUser { Username = "bot" }, Body = MergeRequestAutomationBudget.Marker("review", 2) }
        };
        Assert.AreEqual(0, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "review"));
        Assert.AreEqual(0, MergeRequestAutomationBudget.UsedRounds(notes, "bot", "repair"));
    }

    [TestMethod]
    public void LegacyRepairCommitsCountButOriginalIssueImplementationDoesNot()
    {
        var commits = new[]
        {
            new GitLabCommit { Message = "Fix for issue #2\nAutomatically generated by Agent Bot." },
            new GitLabCommit { Message = "Address MR #1 review: explicit human request\nAutomatically generated fix by Agent Bot." },
            new GitLabCommit { Message = "Fix pipeline failure for MR #1\nAutomatically generated fix by Agent Bot." },
            new GitLabCommit { Message = "Resolve merge conflicts for MR #1\nAutomatically generated fix by Agent Bot." }
        };
        Assert.AreEqual(2, MergeRequestAutomationBudget.UsedRounds([], "bot", "repair", commits));
    }

    [TestMethod]
    public void LimitNoticeIsScopedToBotAndOperation()
    {
        var notes = new[] { Own(MergeRequestAutomationBudget.LimitMarker("review")) };
        Assert.IsTrue(MergeRequestAutomationBudget.LimitAlreadyReported(notes, "BOT", "review"));
        Assert.IsFalse(MergeRequestAutomationBudget.LimitAlreadyReported(notes, "bot", "repair"));
    }

    private static GitLabNote Own(string body) => new()
    {
        Author = new GitLabUser { Username = "bot" }, Body = body
    };
}
